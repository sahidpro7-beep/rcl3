export function translateRole(role: PlayerRole, lang: Language): string {
  return TRANSLATIONS[lang].registration.roles[role] ?? role;
}

export function getApplicationStatusTextClass(status: ApplicationStatus): string {
  if (status === 'approved') return 'text-green-600';
  if (status === 'rejected') return 'text-red-600';
  return 'text-orange-600';
}

export function getPaymentStatusTextClass(status: PaymentStatus): string {
  if (status === 'verified') return 'text-green-600';
  if (status === 'rejected') return 'text-red-600';
  return 'text-orange-600';
}
